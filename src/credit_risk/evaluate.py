from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
from sklearn.metrics import (
    average_precision_score,
    brier_score_loss,
    classification_report,
    confusion_matrix,
    roc_auc_score,
    roc_curve,
)

@dataclass
class EvaluationResult:
    model_name: str
    roc_auc: float
    average_precision: float
    ks_statistic: float
    brier_score: float
    threshold: float
    confusion: np.ndarray
    report: str = field(repr=False)

    def summary_row(self) -> dict[str, float | str]:
        return {
            "Model": self.model_name,
            "ROC-AUC": round(self.roc_auc, 4),
            "PR-AUC": round(self.average_precision, 4),
            "KS": round(self.ks_statistic, 4),
            "Brier": round(self.brier_score, 4),
        }

def ks_statistic(y_true: np.ndarray, y_score: np.ndarray) -> float:
    fpr, tpr, _ = roc_curve(y_true, y_score)
    return float(np.max(tpr - fpr))

def evaluate_model(
    model_name: str,
    y_true: np.ndarray,
    y_score: np.ndarray,
    threshold: float = 0.5,
) -> EvaluationResult:
    """Compute the full metric suite for one model's scored predictions.

    Parameters
    ----------
    model_name:
        Human-readable label.
    y_true:
        Ground-truth binary labels.
    y_score:
        Predicted probability of default (positive class).
    threshold:
        Probability cutoff for the confusion matrix / classification report.
    """
    y_true = np.asarray(y_true)      # ground truth binary labels
    y_score = np.asarray(y_score)    # predicted probability of default
    y_pred = (y_score >= threshold).astype(int) # probability cutoff for the confusion matrix / classification report

    return EvaluationResult(
        model_name=model_name,
        roc_auc=roc_auc_score(y_true, y_score),
        average_precision=average_precision_score(y_true, y_score),
        ks_statistic=ks_statistic(y_true, y_score),
        brier_score=brier_score_loss(y_true, y_score),
        threshold=threshold,
        confusion=confusion_matrix(y_true, y_pred),
        report=classification_report(y_true, y_pred, digits=3, zero_division=0),
    )
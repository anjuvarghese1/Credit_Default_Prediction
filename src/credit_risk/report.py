from __future__ import annotations

import logging
from pathlib import Path

from .config import REPORTS_DIR
from .evaluate import EvaluationResult

logger = logging.getLogger(__name__)

def write_report(
    results: dict[str, EvaluationResult],
    cv_scores: dict[str, tuple[float, float]],
    best_name: str,
    figures: dict[str, Path],
    n_train: int,
    n_test: int,
    default_rate: float,
    out_path: Path | None = None,
) -> Path:
    """Render the benchmark report to Markdown and return its path."""
    out_path = out_path or (REPORTS_DIR / "report.md")

    lines: list[str] = []
    lines.append("# Credit Default Prediction -- Benchmark Report\n")
    lines.append(
        "Automatically generated by `credit_risk.train`. All metrics are on a "
        "held-out test split that the models never saw during training or "
        "cross-validation.\n"
    )

    # Dataset section
    lines.append("## Dataset\n")
    lines.append(
        f"- Training rows: **{n_train:,}**  \n"
        f"- Test rows: **{n_test:,}**  \n"
        f"- Overall default rate: **{default_rate:.2%}** (class-imbalanced)\n"
    )
    lines.append(
        "The target is `SeriousDlqin2yrs` (90+ days past due within two "
        "years). Because defaults are rare, accuracy is not a meaningful "
        "metric; the comparison below uses ranking and calibration metrics "
        "instead.\n"
    )

    # Results table
    lines.append("## Model Comparison\n")
    lines.append(
        "| Model | CV ROC-AUC | Test ROC-AUC | PR-AUC | KS | Brier |\n"
        "|---|---|---|---|---|---|"
    )
    for name, res in results.items():
        cv_mean, cv_std = cv_scores[name]
        marker = " **(best)**" if name == best_name else ""
        lines.append(
            f"| {name}{marker} | {cv_mean:.3f} ± {cv_std:.3f} | "
            f"{res.roc_auc:.3f} | {res.average_precision:.3f} | "
            f"{res.ks_statistic:.3f} | {res.brier_score:.3f} |"
        )
    lines.append("")
    lines.append(
        "_ROC-AUC and KS measure ranking/separation; PR-AUC is the "
        "imbalance-aware precision/recall summary; Brier measures probability "
        "calibration (lower is better)._\n"
    )

    # Interpretation
    lines.append("## Interpretation\n")
    lines.append(
        f"On this structured, tabular dataset the **{best_name}** model gives "
        "the best held-out ranking performance. This is the expected outcome: "
        "gradient-boosted decision trees capture the non-linear, "
        "interaction-heavy structure of credit features more effectively than "
        "a linear model, and they are far less finicky than a neural network "
        "on modest-sized tabular data. The takeaway is not 'deep learning is "
        "bad' but that **model choice should follow the data**: for tabular "
        "credit risk, tree ensembles remain the strong default, while the "
        "logistic regression baseline stays valuable wherever coefficient-level "
        "interpretability is a regulatory requirement.\n"
    )

    # Figures
    lines.append("## Figures\n")
    rel = lambda p: _relative(p, out_path.parent)  # noqa: E731
    lines.append(f"### ROC Curves\n\n![ROC curves]({rel(figures['roc'])})\n")
    lines.append(
        f"### Precision-Recall Curves\n\n![PR curves]({rel(figures['pr'])})\n"
    )
    lines.append(
        f"### Calibration\n\n![Calibration]({rel(figures['calibration'])})\n"
    )
    lines.append(
        f"### Feature Importance ({best_name})\n\n"
        f"![Permutation importance]({rel(figures['importance'])})\n"
    )

    out_path.write_text("\n".join(lines))
    logger.info("Saved report -> %s", out_path)
    return out_path

def _relative(target: Path, start: Path) -> str:
    try:
        return target.relative_to(start).as_posix()
    except ValueError:
        return target.as_posix()